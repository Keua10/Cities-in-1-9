/**
 * 2단계(대형) 시설 (피드백 2차): 특수 건물이 아니면 대도시용 큰 건물이 하나 더 있다.
 * 같은 일을 하고(서비스 채널·배관·전력 같은 종류), 크고(모두 4×4) 정원이 많고 늦게 열린다.
 *
 *   62 대형 소방서   ← 0 소방서        66 대형 소각장   ← 14 쓰레기 소각시설
 *   63 경찰청       ← 1 경찰서        67 대형 화장장   ← 15 화장시설
 *   64 종합병원      ← 2 병원          68 추모공원     ← 16 공동묘지
 *   65 대학교       ← 3 학교          69 광역 교도소   ← 20 교도소
 *   70 대형 취수장   ← 8 하천 취수장    72 풍력 단지     ← 11 풍력 발전소
 *   71 대형 하수처리장 ← 10 하수처리장   73 복합화력 발전소 ← 12 가스 발전소
 *                                    74 대형 태양광 단지 ← 13 태양광 발전소
 */
export const TIER2_BASE: Readonly<Record<number, number>> = {
  62: 0,
  63: 1,
  64: 2,
  65: 3,
  66: 14,
  67: 15,
  68: 16,
  69: 20,
  70: 8,
  71: 10,
  72: 11,
  73: 12,
  74: 13,
};

/** 2단계 시설이면 1단계 종류, 아니면 그대로. 서비스·배관·전력·오염 판정은 이 값으로 한다. */
export function baseKind(kind: number): number {
  return TIER2_BASE[kind] ?? kind;
}

/** 1단계 → 2단계 종류(있으면). */
export const TIER2_OF: Readonly<Record<number, number>> = Object.fromEntries(
  Object.entries(TIER2_BASE).map(([t2, b]) => [b, Number(t2)]),
);

/**
 * 재정 밸런스: "웬만해선 적자가 나지 않고, 잘 운영하면 훨씬 잘 번다."
 *
 *  1. 이용률 연동 운영비 — 서비스·상하수도·발전 시설은 일이 없으면 운영비가 적게 든다.
 *     빈 소방서는 IDLE_UPKEEP_SHARE(30%)만 내고, 담당 구역이 꽉 차면 100%를 낸다.
 *     도시보다 시설을 먼저 지어도 적자로 무너지지 않는다.
 *  2. 중앙정부 지원금 — 그래도 모자라면 정부가 메워 준다. 한도는 운영비의
 *     GRANT_UPKEEP_SHARE + GRANT_BASE 까지라, 터무니없이 과하게 지은 도시만 적자가 난다.
 *     전쟁 같은 특수 상황에서는 끊긴다(전쟁 단계에서 연결).
 *  3. 세금 — 잘 운영한 도시(입주율·건물 등급이 높은 도시)가 확실히 남기도록 넉넉하게.
 *
 * 저장되지 않는 값이라 마음껏 고쳐도 된다.
 */

/** 일이 하나도 없는 시설이 내는 운영비 비율. 나머지는 이용률에 비례한다. */
export const IDLE_UPKEEP_SHARE = 0.3;

/** 정부 지원금 한도 = 운영비 × 이 비율 + GRANT_BASE (만 원/일). */
export const GRANT_UPKEEP_SHARE = 0.6;
export const GRANT_BASE = 500;

/** 세금 배수. 세율 정책(기본 9%)과 곱해진다. */
export const TAX_MULTIPLIER = 1.3;
